/** Exercise optional briefing UI with real containers; no browser-layout claim. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {JSDOM, VirtualConsole} from 'jsdom';
import {mountClassicRemaster} from '../assets/classic-remaster-ui.js';
const errors=[];
const virtualConsole=new VirtualConsole().on('jsdomError',error=>errors.push(error));
const html=fs.readFileSync(new URL('../index.html',import.meta.url),'utf8');
const atlas=JSON.parse(fs.readFileSync(new URL('../assets/classic-route-atlas.json',import.meta.url),'utf8'));
const dom=new JSDOM(html,{url:'https://omoji-z.example/',pretendToBeVisual:true,virtualConsole});
const win=dom.window,doc=win.document;
let next=0;const frames=new Map();
win.requestAnimationFrame=fn=>{frames.set(++next,fn);return next;};
win.cancelAnimationFrame=id=>frames.delete(id);
async function flush(){
  for(let i=0;i<8;i++){
    await new Promise(resolve=>setImmediate(resolve));
    if(!frames.size)continue;
    const todo=[...frames.values()];frames.clear();todo.forEach(fn=>fn());
  }
  assert.equal(frames.size,0,'observers settle');
}
const track=doc.querySelector('#track-list');
track.innerHTML='<button data-track="haruna" aria-pressed="true"><strong class="track-name">銀樹峠</strong><span class="track-detail">夜・ドライ · 3.2 km</span></button>';
const fixture=()=>({ok:true,json:async()=>atlas});
let requests=0;
win.fetch=async()=>{requests++;throw new Error('offline');};
const mounted=mountClassicRemaster(doc);
await flush();
const retry=doc.querySelector('.remaster-map-retry'),status=doc.querySelector('.remaster-map-status');
assert.equal(status.dataset.state,'failed');
assert.match(status.textContent,/走行は開始できます/);
assert.equal(retry.hidden,false);
assert.equal(doc.querySelector('.remaster-map-open').hidden,true);
win.fetch=async()=>{requests++;return fixture();};
retry.click();await flush();
assert.equal(requests,2);assert.equal(retry.hidden,true);assert.equal(status.dataset.state,'ready');
const open=doc.querySelector('.remaster-map-open'),dialog=doc.querySelector('#remaster-route-dialog');
assert.equal(open.hidden,false);assert.equal(open.getAttribute('aria-haspopup'),'dialog');
open.focus();open.click();
assert.equal(dialog.open,true);assert.equal(doc.activeElement,dialog.querySelector('button'));
assert.equal(dialog.querySelector('h2').textContent,'銀樹峠');
assert.equal(dialog.querySelector('.remaster-map-caption strong').textContent,'3.2 km');
assert.match(dialog.querySelector('.remaster-map-detail').textContent,/夜・ドライ/);
assert.equal(dialog.querySelectorAll('svg [id]').length,0,'Cloning route must not duplicate IDs');
assert.equal(dialog.querySelectorAll('svg .remaster-route-start').length,1);
assert.equal(dialog.querySelectorAll('svg .remaster-route-end').length,1);
dialog.dispatchEvent(new win.KeyboardEvent('keydown',{key:'Tab',bubbles:true,cancelable:true}));
assert.equal(doc.activeElement,dialog.querySelector('button'));
dialog.dispatchEvent(new win.KeyboardEvent('keydown',{key:'Escape',bubbles:true,cancelable:true}));
assert.equal(dialog.open,false);assert.equal(doc.activeElement,open,'Escape restores opener focus');
const race=doc.querySelector('#race');
await flush();
const queuedBeforeHUD = next;
for(let frame=0;frame<120;frame++)doc.querySelector('#race-time').textContent=String(frame);
await new Promise(resolve=>setImmediate(resolve));
assert.equal(next,queuedBeforeHUD,'High-frequency HUD text must not schedule briefing work');
race.hidden=false;open.click();assert.equal(dialog.open,false,'Cannot open briefing while racing');
let clicks=0;const first=doc.querySelector('.simple-nav a');first.addEventListener('click',event=>{event.preventDefault();clicks++;});
const alt=()=>doc.body.dispatchEvent(new win.KeyboardEvent('keydown',{key:'1',altKey:true,bubbles:true,cancelable:true}));
alt();assert.equal(clicks,0,'Navigation shortcut cannot interrupt active race');
race.hidden=true;alt();await flush();assert.equal(clicks,1);assert.equal(doc.activeElement,doc.querySelector('#setup h2'));
assert.equal(first.getAttribute('aria-keyshortcuts'),'Alt+1');
open.click();assert(dialog.open);race.hidden=false;await flush();assert(!dialog.open,'Starting a race closes the briefing');
race.hidden=true;await flush();
open.click();assert(dialog.open);race.setAttribute('open','');await flush();assert(!dialog.open,'Open attribute closes the briefing without a HUD mutation');
race.removeAttribute('open');await flush();
track.innerHTML='<button data-track="enkan-circuit" aria-pressed="true"><strong class="track-name">凪輪サーキット</strong></button>';
await flush();open.click();
assert.match(dialog.querySelector('.remaster-map-caption span').textContent,/兼用/);
assert.equal(dialog.querySelector('.remaster-route-end').style.display,'none','A closed circuit has one shared start/finish marker');
assert.equal(dialog.querySelector('.remaster-route-start').style.display,'');
dialog.querySelector('button').click();
track.innerHTML='<button data-track="haruna" aria-pressed="true"><strong class="track-name">銀樹峠</strong></button>';await flush();
mounted.destroy();await flush();assert(!doc.querySelector('#remaster-route-dialog'));assert(!first.hasAttribute('aria-keyshortcuts'));assert(!doc.querySelector('#setup h2').hasAttribute('tabindex'));

// Timed-out requests may finish late; that response must not replace a retry result.
let finishOld, timeoutCallback;
const setTimeoutOriginal=win.setTimeout.bind(win),clearTimeoutOriginal=win.clearTimeout.bind(win);
win.setTimeout=(fn,delay)=>delay===8000?(timeoutCallback=fn,412):setTimeoutOriginal(fn,delay);
win.clearTimeout=id=>{if(id!==412)clearTimeoutOriginal(id);};
win.fetch=()=>new Promise(resolve=>{finishOld=resolve;});
const stale=mountClassicRemaster(doc);timeoutCallback();
assert.equal(doc.querySelector('.remaster-map-status').dataset.state,'failed');
win.fetch=async()=>fixture();doc.querySelector('.remaster-map-retry').click();await flush();
finishOld({ok:true,json:async()=>({haruna:{path:atlas.haruna.path,length:'not a distance'}})});await flush();
assert.equal(doc.querySelector('#remaster-route-distance').textContent,'3.2 km');
stale.destroy();await flush();
assert.equal(errors.length,0);
dom.window.close();
console.log('Quality UI passed: atlas failure/retry/timeout/stale-response handling, real route briefing, endpoint markers, focus restore/containment, race boundaries, zero HUD refresh work, closed-circuit marker, keyboard navigation, cleanup and no jsdom errors.');
